// Service worker minimal : condition technique pour l'installation en PWA,
// et mise en cache légère du carnet pour un chargement plus rapide sur les
// visites suivantes. Ne gère pas de vraie édition hors-ligne (le carnet a
// besoin du réseau pour lire/écrire le stockage partagé) — juste le shell.
const CACHE_NAME = 'carnet-shell-v1';
const SHELL_FILES = ['./carnet-artiste.html', './manifest.json', './icon-192.png', './icon-512.png'];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(SHELL_FILES)).catch(() => {})
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k)))
    )
  );
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') return;
  event.respondWith(
    fetch(event.request)
      .then((res) => {
        const resClone = res.clone();
        caches.open(CACHE_NAME).then((cache) => cache.put(event.request, resClone)).catch(() => {});
        return res;
      })
      .catch(() => caches.match(event.request))
  );
});
